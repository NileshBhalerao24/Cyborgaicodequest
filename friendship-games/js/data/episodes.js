export const episodeById = Object.fromEntries(EPISODES.map((e) => [e.id, e]));

export function castOf(ep) {
  const ids = new Set();
  const walk = (b) => {
    if (b.par) b.par.forEach(walk);
    if (b.seq) b.seq.forEach(walk);
    for (const k of ['say', 'enter']) if (typeof b[k] === 'string') ids.add(b[k]);
    if (b.spawn) ids.add(b.spawn.id);
  };
  for (const s of ep.scenes) { Object.keys(s.cast || {}).forEach((id) => ids.add(id)); s.beats.forEach(walk); }
  return [...ids];
}
